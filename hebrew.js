// Strips niqqud so near-duplicate words/phrases can be compared
function stripNiqqud(s) {
    return s.replace(/[֑-ׇ]/g, '').normalize('NFC');
}

// Wrong answers share the entry's part of speech: same unit first, then other units
function pickDistractors(entry, pools, key, count) {
    const used = new Set([stripNiqqud(key(entry)), stripNiqqud(entry[1])]);
    const words = entry[1].split(' ').length;
    const result = [];
    for (const pool of pools) {
        const candidates = pool
            .filter(e => e !== entry)
            .map(e => ({ e, score: Math.abs(e[1].split(' ').length - words) + Math.random() * 2 }))
            .sort((a, b) => a.score - b.score);
        for (const { e } of candidates) {
            if (result.length === count) return result;
            const k = stripNiqqud(key(e));
            if (used.has(k) || used.has(stripNiqqud(e[1]))) continue;
            used.add(k);
            used.add(stripNiqqud(e[1]));
            result.push(key(e));
        }
    }
    return result;
}

// Removes parenthetical examples, which often contain the answer itself
function hideHints(meaning) {
    const stripped = meaning.replace(/\s*\([^)]*\)/g, '').trim();
    return stripped || meaning;
}

